"""Reversal-strategy analytics surface (post-audit, full 7-asset dataset).

Runs the rigorous re-analysis and writes a human-readable report to
`research/reversal_analysis.md` plus figures to `research/figures/`. Re-run any
time the cache grows:  python analyze_reversal.py

Numbers here use the REALISTIC entry (buy at the earliest ask-lift print, truncated
windows excluded) and report the cluster-robust t-stat (clustered by wall-clock
window) alongside the naive one. See research/reversal_audit.md for why.
"""
from __future__ import annotations

import math
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from polymarket_arb import (MomentumBacktester, MomentumConfig, autocorr_table,
                            block_bootstrap, friction_grid, load_all, sample_decay)

OUT_MD = Path("research/reversal_analysis.md")
FIGDIR = Path("research/figures")
FIGDIR.mkdir(parents=True, exist_ok=True)


def fmt(x, n=3):
    return "nan" if x != x else f"{x:.{n}f}"


def main():
    data = load_all(count=500)
    allw = [w for ws in data.values() for w in ws]
    n_trunc = sum(1 for w in allw if w.truncated)

    ac = autocorr_table(data)
    decay = sample_decay(data)
    rev = friction_grid(allw, "reversal")
    rev_opt = friction_grid(allw, "reversal", cfg_kw={"entry_side": "any"})  # old optimistic
    mom = friction_grid(allw, "momentum")

    # headline scenario: realistic entry, 0 extra spread, 0 fee (most generous realistic)
    res0 = MomentumBacktester(MomentumConfig(direction="reversal")).run(allw)
    bt = MomentumBacktester(MomentumConfig(direction="reversal"))
    bt.run(allw)
    boot = block_bootstrap([r.pnl for r in res0], [r.start_ts for r in res0])

    # ---- figures ----
    aa = [r for r in ac if r["asset"] != "ALL"]
    plt.figure(figsize=(7, 3.2))
    colors = ["tab:red" if r["lag1_autocorr"] < 0 else "tab:green" for r in aa]
    plt.bar([r["asset"] for r in aa], [r["lag1_autocorr"] for r in aa], color=colors)
    plt.axhline(0, c="grey", lw=.8)
    plt.ylabel("lag-1 autocorrelation"); plt.title("Per-asset outcome autocorrelation (red=reversion, green=momentum)")
    plt.tight_layout(); plt.savefig(FIGDIR / "autocorr_by_asset.png", dpi=110); plt.close()

    plt.figure(figsize=(6, 3.2))
    plt.plot([d["label"] for d in decay], [d["z"] for d in decay], "o-")
    plt.axhline(-1.96, c="red", ls="--", lw=.8, label="z=-1.96")
    plt.ylabel("pooled autocorr z"); plt.xticks(rotation=20, ha="right")
    plt.title("Signal decays as the sample deepens & widens"); plt.legend()
    plt.tight_layout(); plt.savefig(FIGDIR / "sample_decay.png", dpi=110); plt.close()

    spreads = sorted({r["half_spread"] for r in rev})
    plt.figure(figsize=(6, 3.2))
    for fee in sorted({r["fee_bps"] for r in rev}):
        ys = [next((r["avg_pnl"] for r in rev if r["half_spread"] == s and r["fee_bps"] == fee), None)
              for s in spreads]
        plt.plot(spreads, ys, "o-", label=f"{fee}bps fee")
    plt.axhline(0, c="grey", lw=.8)
    plt.xlabel("entry half-spread added"); plt.ylabel("avg PnL / bet")
    plt.title("Reversal edge vs friction (realistic ask entry)"); plt.legend()
    plt.tight_layout(); plt.savefig(FIGDIR / "reversal_vs_friction.png", dpi=110); plt.close()

    # ---- markdown ----
    def actable(rows):
        out = ["| asset | n_pairs | autocorr | z | base_up | P(Up\\|Up) | P(Up\\|Dn) | repeat |",
               "|---|---|---|---|---|---|---|---|"]
        for r in rows:
            out.append(f"| {r['asset']} | {r['n_pairs']} | {fmt(r['lag1_autocorr'])} | "
                       f"{fmt(r['z'],2)} | {fmt(r['base_up_rate'])} | {fmt(r['p_up_after_up'])} | "
                       f"{fmt(r['p_up_after_down'])} | {fmt(r['repeat_rate'])} |")
        return "\n".join(out)

    def ftable(rows):
        out = ["| half_spread | fee_bps | n | win | avg_entry | avg_pnl | t_naive | t_clustered |",
               "|---|---|---|---|---|---|---|---|"]
        for r in rows:
            out.append(f"| {fmt(r['half_spread'],3)} | {r['fee_bps']} | {r['n']} | "
                       f"{fmt(r['win_rate'])} | {fmt(r['avg_entry'])} | {fmt(r['avg_pnl'],4)} | "
                       f"{fmt(r['t_naive'],2)} | {fmt(r['t_clustered'],2)} |")
        return "\n".join(out)

    dtable = "\n".join(
        ["| sample | n_pairs | autocorr | z |", "|---|---|---|---|"] +
        [f"| {d['label']} | {d['n_pairs']} | {fmt(d['lag1_autocorr'])} | {fmt(d['z'],2)} |"
         for d in decay])

    md = f"""# Reversal Strategy — Analytics (post-audit, full dataset)

*Auto-generated by `analyze_reversal.py`. Methodology audit: `research/reversal_audit.md`.*

## Dataset
{len(allw)} resolved windows across {len(data)} assets ({", ".join(data)}); ~{sum(len(v) for v in data.values())//len(data)} per asset.
Truncated windows (tape hit the API offset cap): {n_trunc} ({100*n_trunc/len(allw):.1f}%) — excluded from the backtest.

## 1. Is the signal real? (lag-1 autocorrelation of outcomes — uses NO prices)
{actable(ac)}

Negative = mean-reversion (a win tends to follow a loss). The pooled effect is small
and **not uniform**: most assets are weakly negative, **xrp ≈ 0**, and **hype is
positive** (momentum, not reversion). The pooled z below is the *naive* z; it is
inflated because all 7 assets share clock-aligned windows (cross-asset correlation).

## 2. The earlier "significant" result was a small-sample / few-assets artifact
{dtable}

The first study used the most-recent ~250 windows of 5 highly-correlated majors and
the naive z; deepening to 500/asset and adding 2 less-correlated assets washes the
signal out toward the significance line.

![autocorr by asset](figures/autocorr_by_asset.png)
![sample decay](figures/sample_decay.png)

## 3. Is it tradeable? Reversal PnL vs friction (REALISTIC ask entry)
`t_clustered` clusters by wall-clock window (captures cross-asset + serial dependence).
{ftable(rev)}

**Block bootstrap** (resampling whole wall-clock windows, headline 0-spread/0-fee
scenario): mean PnL/bet {fmt(boot['mean'],4)}, 95% CI [{fmt(boot['lo'],4)}, {fmt(boot['hi'],4)}],
P(mean ≤ 0) = {fmt(boot['p_le_0'],3)}.

![reversal vs friction](figures/reversal_vs_friction.png)

## 4. For contrast: the OLD optimistic entry (buy at earliest print, side-blind)
{ftable(rev_opt)}

The difference between §3 and §4 is the audit's #1 fix (you cannot buy at a SELL/bid
print). Realistic entry alone removes most of the apparent edge.

## 5. Momentum (opposite bet), realistic entry
{ftable(mom)}

## Verdict
The negative-autocorrelation *phenomenon* is genuine and look-ahead-free, but it is
**weak, unstable across assets, and not tradeable** after realistic ask entry and
costs: the cluster-robust t-stat does not clear 2 even at zero fee/zero added spread,
and any friction pushes it negative. The earlier +$0.038/bet (t≈2.7) result does not
survive ~3× more data, two additional assets, side-correct entry, and a
dependence-robust standard error.
"""
    OUT_MD.write_text(md)
    print(md)
    print(f"\nWrote {OUT_MD} and 3 figures to {FIGDIR}/")


if __name__ == "__main__":
    main()
