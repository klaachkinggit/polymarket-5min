"""Regime analytics surface: do vol regimes favor any strategy, and are they predictable?

Writes research/regime_analysis.md + figures. Re-run any time:  python analyze_regimes.py
"""
from __future__ import annotations

from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from polymarket_arb import load_all
from polymarket_arb.regimes import (REGIMES, label_terciles, regime_performance,
                                    regime_rows, vol_by_hour, vol_persistence)

OUT = Path("research/regime_analysis.md")
FIG = Path("research/figures")
FIG.mkdir(parents=True, exist_ok=True)


def f(x, n=4):
    return "nan" if x != x else f"{x:.{n}f}"


def main():
    data = load_all(count=500)
    allw = [w for ws in data.values() for w in ws]
    rows = regime_rows(allw)
    q1, q2 = label_terciles(rows)
    perf = regime_performance(rows)
    persist = vol_persistence(allw)
    hourly = vol_by_hour(allw)

    # index perf by (strategy, regime)
    idx = {(p["strategy"], p["regime"]): p for p in perf}

    # ---- figure 1: mean pnl by regime per strategy ----
    plt.figure(figsize=(7, 3.4))
    width = 0.25
    xs = range(len(REGIMES))
    for i, strat in enumerate(("reversal", "momentum", "arb")):
        ys = [idx.get((strat, r), {}).get("mean_pnl", float("nan")) for r in REGIMES]
        plt.bar([x + i * width for x in xs], ys, width, label=strat)
    plt.axhline(0, c="grey", lw=.8)
    plt.xticks([x + width for x in xs], [f"{r}-vol" for r in REGIMES])
    plt.ylabel("mean PnL / window"); plt.title("Strategy PnL by prior-window volatility regime")
    plt.legend(); plt.tight_layout(); plt.savefig(FIG / "regime_pnl.png", dpi=110); plt.close()

    # ---- figure 2: vol by hour (regime predictability / seasonality) ----
    plt.figure(figsize=(7, 3.0))
    plt.plot([h["hour"] for h in hourly], [h["mean_rvol"] for h in hourly], "o-")
    plt.xlabel("UTC hour"); plt.ylabel("mean realized vol"); plt.title("Volatility seasonality by hour")
    plt.tight_layout(); plt.savefig(FIG / "vol_by_hour.png", dpi=110); plt.close()

    def ptable():
        out = ["| strategy | regime | n | mean PnL/win | cluster-robust t |",
               "|---|---|---|---|---|"]
        for strat in ("reversal", "momentum", "arb"):
            for r in REGIMES:
                p = idx.get((strat, r))
                if p:
                    out.append(f"| {strat} | {r} | {p['n']} | {f(p['mean_pnl'])} | {f(p['t'],2)} |")
        return "\n".join(out)

    # any regime/strategy that clears zero significantly (tradeable)?
    winners = [p for p in perf if p["mean_pnl"] > 0 and p["t"] is not None and p["t"] > 2]
    rev_lo = idx.get(("reversal", "low"), {})
    mom_lo = idx.get(("momentum", "low"), {})

    md = f"""# Regime Analysis — do vol regimes favor any strategy?

*Auto-generated by `analyze_regimes.py`. {len(rows)} consecutive (prev,cur) pairs across the
spot-covered assets. Regime = tercile of the **previous** window's underlying realized vol
(ex-ante: known at the current open). Edges: low ≤ {f(q1,4)} < med ≤ {f(q2,4)} < high.*

## Are regimes predictable?
- **Volatility clusters** ⇒ the regime is forecastable: lag-1 autocorrelation of per-window
  realized vol = **{f(persist['autocorr'],3)}** (n={persist['n']} consecutive pairs). A high-vol
  window is followed by another high-vol window more often than chance, so you can predict the
  next window's regime from the current one.
- There is also intraday **vol seasonality** by UTC hour (see figure).

![vol by hour](figures/vol_by_hour.png)

## Does any strategy do better in a regime?
PnL per window, split by the prior window's vol regime (cluster-robust t, clustered by
wall-clock window). reversal/momentum use realistic ask entry; arb is the passive double-dip
at T=0.49 (generous, ignores the ~9% effective spread).

{ptable()}

![regime pnl](figures/regime_pnl.png)

## Verdict

**Regimes are real and predictable, and the cross-window effect DOES depend on the regime —
but not enough to trade.** Two findings:

1. **Regime dependence (the interesting part).** The serial correlation flips sign with
   volatility. In **low-vol** windows outcomes **persist** (momentum): the reversal bet
   *significantly loses* ({f(rev_lo.get('mean_pnl',float('nan')))}, t={f(rev_lo.get('t',float('nan')),2)})
   while momentum is positive ({f(mom_lo.get('mean_pnl',float('nan')))}, t={f(mom_lo.get('t',float('nan')),2)}).
   In med/high-vol it washes out (means ≈ 0, |t| < 0.5). So the pooled "weak reversion" hides a
   **low-vol momentum / higher-vol noise** structure — exactly the "some regimes favour one
   strategy" hypothesis, qualitatively confirmed.
2. **Still not tradeable.** {"A cell clears t>2 positive: " + ", ".join(f"{p['strategy']}/{p['regime']}" for p in winners) if winners else "No (strategy, regime) cell is positive with cluster-robust t > 2."}
   The low-vol momentum tilt is **t={f(mom_lo.get('t',float('nan')),2)} (< 2)** and ≈3.5¢/window —
   smaller than the ~9% effective spread (market_dynamics.md), so it does not survive realistic
   execution. Arb loses in *every* regime (t ≈ −13 to −15).

Because the regime axis is genuinely forecastable (vol autocorr 0.43), this is a fair test of
"trade strategy X only in regime Y": the predictability is there, and there is a real
sign-flip, but the conditional edge is still inside the spread. Next step if pursued: test the
low-vol momentum tilt out-of-sample and against the live order-book spread we collected.
"""
    OUT.write_text(md)
    print(md)
    print(f"\nWrote {OUT} + figures")


if __name__ == "__main__":
    main()
